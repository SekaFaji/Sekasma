export type ArgonCreature = "palm" | "drone";
/** Draw each owned helper once per frame; strike effects are separately bounded. */
export function drawArgonCreature(
  ctx: CanvasRenderingContext2D,
  kind: ArgonCreature, x: number, y: number, t: number,
  index: number, striking: boolean,
): void {
  const palm = kind === "palm";
  const frames = palm ? CONDUCTIVE_PALM_FRAMES : ORBIT_DRONE_FRAMES;
  const phase = Math.sin(t * (palm ? 8 : 10) + index * 1.93);
  const sprite = frames[striking ? 2 : phase > 0 ? 0 : 1];
  drawSprite(ctx, sprite, x - Math.floor(sprite[0].length / 2), y - Math.floor(sprite.length / 2),
    palm ? PALM_PALETTE : DRONE_PALETTE);
  if (striking) {
    ctx.fillStyle = "#d9faff";
    ctx.fillRect(Math.round(x) - 1, Math.round(y) - 1, 2, 2);
    ctx.fillStyle = "#828cff";
    ctx.fillRect(Math.round(x) + (palm ? 5 : 7), Math.round(y), 1, 1);
  }
}
